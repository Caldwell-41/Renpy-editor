import assert from "node:assert/strict";

export default async function check({ page, open }) {
  for (const variant of ["workbench", "focus"]) {
    const load = async (options = {}) => {
      await page.setViewportSize(options.viewport === "compact" ? { width: 560, height: 640 } : { width: 1100, height: 720 });
      await open({ screen: "source", variant, ...options });
    };
    const editor = () => page.locator(".sl-editor");
    const save = () => page.getByRole("button", { name: "Save source", exact: true });
    const files = async () => { if (!(await page.getByRole("button", { name: "Files", exact: true }).getAttribute("aria-expanded") === "true")) await page.getByRole("button", { name: "Files", exact: true }).click(); };
    const select = async path => { await files(); await page.locator(`.sl-file[data-path="${path}"]`).click(); };
    const saved = async () => { await page.locator('.sl-workspace[data-busy="false"]').waitFor(); assert.match(await page.locator(".lp-status").innerText(), /Saved in sample/); };
    await load();
    const original = await editor().inputValue();
    assert.equal(await save().isDisabled(), true);
    const draft = original + "\n# Café 雪. Retain this unsaved ending.\n";
    await editor().fill(draft);
    await editor().evaluate(e => { e.focus(); e.setSelectionRange(9, 18); });
    await select("game/sealed_letter.rpy");
    await editor().fill('label sealed_letter:\n    "A second draft."\n');
    await select("game/last_service.rpy");
    assert.equal(await editor().inputValue(), draft);
    assert.deepEqual(await editor().evaluate(e => [e.selectionStart, e.selectionEnd, document.activeElement === e]), [9, 18, true]);
    await page.getByRole("button", { name: "Undo", exact: true }).click(); assert.equal(await editor().inputValue(), original);
    await page.getByRole("button", { name: "Redo", exact: true }).click(); assert.equal(await editor().inputValue(), draft);
    await save().click(); await saved();
    await select("game/sealed_letter.rpy"); assert.match(await editor().inputValue(), /A second draft/);
    await page.getByRole("button", { name: "Close sealed_letter.rpy tab; keep draft", exact: true }).click();
    await select("game/sealed_letter.rpy"); assert.match(await editor().inputValue(), /A second draft/);
    await page.getByRole("button", { name: "Discard draft", exact: true }).click();
    await page.getByRole("button", { name: "Keep editing", exact: true }).click(); assert.match(await editor().inputValue(), /A second draft/);
    await page.getByRole("button", { name: "Discard draft", exact: true }).click();
    await page.getByRole("button", { name: "Discard this draft", exact: true }).click(); assert.match(await editor().inputValue(), /addressed to someone/);
    await select("game/last_service.rpy");
    await page.getByRole("button", { name: "Find / replace", exact: true }).click();
    await page.getByRole("searchbox", { name: "Find text", exact: true }).fill("tram");
    assert.match(await page.locator(".sl-find .sl-note").innerText(), /matches/);
    await page.getByRole("button", { name: "Next", exact: true }).click();
    assert.equal(await editor().evaluate(e => e.value.slice(e.selectionStart, e.selectionEnd).toLowerCase()), "tram");
    await page.getByRole("textbox", { name: "Replace with", exact: true }).fill("train");
    await page.getByRole("button", { name: "Replace all", exact: true }).click(); assert.match(await editor().inputValue(), /last train/);
    await page.getByRole("button", { name: "Close find and replace", exact: true }).click();
    await page.getByRole("button", { name: "Scene context", exact: true }).click();
    await page.getByRole("button", { name: "Dialogue · Mara", exact: true }).click();
    assert.match(await editor().evaluate(e => e.value.slice(e.selectionStart, e.selectionEnd)), /mara/);
    await page.getByRole("button", { name: "View selected beat in Story", exact: true }).click();
    await page.getByRole("button", { name: "Back to source", exact: true }).click();
    await page.getByRole("button", { name: "Custom code · Python", exact: true }).click();
    assert.equal(await page.getByRole("button", { name: "View selected beat in Story", exact: true }).isDisabled(), true);
    await page.getByRole("button", { name: "Close scene context", exact: true }).click();
    assert.equal(await page.getByRole("button", { name: "Scene context", exact: true }).evaluate(e => e === document.activeElement), true);
    await page.setViewportSize({ width: 1440, height: 900 });
    await files(); await page.getByRole("button", { name: "Hide source files", exact: true }).click();
    await page.getByRole("button", { name: "Scene context", exact: true }).click();
    const inspector = await page.locator(".sl-context").boundingBox(); const editing = await page.locator(".sl-work").boundingBox();
    assert(inspector && editing && inspector.y < editing.y + 12 && inspector.x >= editing.x && inspector.y + inspector.height <= 900, "Expanded context must remain beside or over the editor");
    await page.getByRole("button", { name: "Close scene context", exact: true }).click();
    await page.setViewportSize({ width: 1100, height: 720 });
    await select("game/screens.rpy"); assert.equal(await editor().getAttribute("readonly"), ""); assert.match(await editor().inputValue(), /screen station_clock/);
    await select("game/old_timetable.rpy"); assert.equal(await page.locator(".sl-unavailable").isVisible(), true);
    await page.getByRole("button", { name: "Retry file", exact: true }).click(); assert.match(await page.locator(".lp-status").innerText(), /still unavailable/);
    await select("game/last_service.rpy"); await files();
    await page.getByRole("searchbox", { name: "Find a file", exact: true }).fill("no-match"); assert.match(await page.locator(".sl-file-rows").innerText(), /No matching/);
    await page.getByRole("searchbox", { name: "Find a file", exact: true }).fill("");
    await page.getByRole("button", { name: "Hide source files", exact: true }).click();
    assert.equal(await page.getByRole("button", { name: "Files", exact: true }).evaluate(e => e === document.activeElement), true);
    await load({ state: "error", theme: "dark", viewport: "compact" });
    await editor().fill(original + "\n# Retry safely\n"); await save().click(); await page.locator('.sl-workspace[data-busy="false"]').waitFor();
    assert.match(await page.locator(".lp-status").innerText(), /Simulated save failure/); assert.match(await editor().inputValue(), /Retry safely/);
    await save().click(); await saved();
    await load({ state: "conflict", theme: "dark", viewport: "compact" });
    assert.equal(await save().isDisabled(), true);
    await page.getByRole("button", { name: "Review changes", exact: true }).click();
    await page.getByText("Review combined result", { exact: true }).click();
    assert.match(await page.locator(".sl-combined").innerText(), /ticket booth/); assert.match(await page.locator(".sl-combined").innerText(), /one minute/);
    await page.getByRole("button", { name: "Apply both", exact: true }).click();
    assert.match(await editor().inputValue(), /ticket booth/); assert.match(await editor().inputValue(), /one minute/);
    await save().click(); await saved();
    await load({ state: "conflict" });
    await page.getByRole("button", { name: "Review changes", exact: true }).click();
    await page.getByRole("button", { name: "Load external instead", exact: true }).click();
    await page.getByRole("button", { name: "Load external version", exact: true }).click();
    assert.match(await editor().inputValue(), /ticket booth/); assert.doesNotMatch(await editor().inputValue(), /one minute/); assert.equal(await save().isDisabled(), true);
    await load({ state: "long", theme: "dark", viewport: "compact" });
    assert(await editor().evaluate(e => e.scrollHeight > e.clientHeight));
    await editor().evaluate(e => { e.scrollTop = 1700; e.setSelectionRange(2500, 2510); });
    await select("game/sealed_letter.rpy"); await select("game/last_service.rpy");
    assert((await editor().evaluate(e => e.scrollTop)) >= 1600);
    const bounds = await save().boundingBox(); assert(bounds && bounds.x >= 0 && bounds.y >= 0 && bounds.x + bounds.width <= 560 && bounds.y + bounds.height <= 640);
    await load({ state: "empty" }); assert.equal(await editor().inputValue(), ""); assert.equal(await page.locator(".sl-empty").isVisible(), true);
    await editor().fill('label new_scene:\n    "A new beginning."\n'); await editor().press("Meta+s"); await saved();
    await load();
  }
}
