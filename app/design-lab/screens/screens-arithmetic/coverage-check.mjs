import assert from 'node:assert/strict';
// Focused design proof at the mounted mock boundary. No runtime assertions.
export default async function({page,open,capture}){
  const variant=await page.locator('#preview').getAttribute('data-variant');
  const formula=n=>page.getByRole('textbox',{name:`Action ${n} formula`,exact:true});
  const operation=page.getByRole('combobox',{name:'Action 1 operation',exact:true});
  await open({state:'button',viewport:'wide'});
  assert.deepEqual(await operation.locator('option').evaluateAll(es=>es.map(e=>e.value)),['=','+=','-=','*=','/=','//=','%=']);
  await formula(1).fill('1');
  await page.getByRole('button',{name:'Apply action draft',exact:true}).click();
  assert.match(await page.locator('.sa-message').innerText(),/No actions ran/);
  // Ordinary division cannot silently become a whole-number result.
  await operation.selectOption('/=');
  assert.match(await page.locator('.sa-diagnostic').first().innerText(),/Decimal result/);
  await page.getByRole('combobox',{name:'Action 1 variable',exact:true}).selectOption('money');
  assert.match(await page.locator('.sa-diagnostic').first().innerText(),/Decimal result → Decimal target/);
  await operation.selectOption('=');
  assert.match(await page.locator('.sa-diagnostic').first().innerText(),/Whole number result → Decimal target/);
  await formula(1).fill('trust + bonus');
  await formula(1).evaluate(e=>{e.focus();e.setSelectionRange(0,e.value.length);});
  await page.getByRole('button',{name:'Group action 1 selection',exact:true}).click();
  assert.equal(await formula(1).inputValue(),'(trust + bonus)');
  assert.equal(await formula(1).evaluate(e=>e===document.activeElement),true);
  await formula(1).fill('(trust + bonus) * 2');
  await page.getByRole('button',{name:'Move action 1 later',exact:true}).click();
  assert.match(await page.locator('.sa-step').nth(1).innerText(),/\(trust \+ bonus\) \* 2/);
  assert.equal(await formula(2).inputValue(),'(trust + bonus) * 2');
  assert.equal(await page.getByRole('button',{name:'Move action 3 earlier',exact:true}).isDisabled(),true);
  await capture(`${variant}-actions-wide`);
  await open({state:'decimal',viewport:'compact'});await capture(`${variant}-decimal-compact`);
  await open({state:'variables',viewport:'wide'});
  const value=page.getByRole('textbox',{name:'Default value',exact:true});
  await value.fill('-');await page.getByRole('button',{name:'Save default',exact:true}).click();
  assert.equal(await value.inputValue(),'-');assert.equal(await value.getAttribute('aria-invalid'),'true');
  await page.getByRole('button',{name:'Edit trust default',exact:true}).click();
  await page.getByRole('button',{name:'Edit money default',exact:true}).click();
  assert.equal(await value.inputValue(),'-');
  await value.fill('2.5');await page.getByRole('button',{name:'Save default',exact:true}).click();
  assert.match(await page.getByRole('button',{name:'Edit money default',exact:true}).innerText(),/2.5/);
  assert.equal(await page.getByRole('combobox',{name:'Variable type',exact:true}).count(),0);
  await page.getByRole('button',{name:'New variable',exact:true}).click();
  await page.getByRole('textbox',{name:'Technical name',exact:true}).fill('fare');
  await value.fill('0.5');await page.getByRole('button',{name:'Create variable',exact:true}).click();
  assert.match(await page.getByRole('button',{name:'Edit fare default',exact:true}).innerText(),/Decimal.*0.5/);
  await capture(`${variant}-variables-wide`);
  await open({state:'condition',viewport:'compact'});
  await page.getByRole('combobox',{name:'Condition variable',exact:true}).selectOption('trust');
  await page.getByRole('textbox',{name:'Condition number',exact:true}).fill('1.25');
  await page.getByRole('button',{name:'Apply condition',exact:true}).click();
  assert.equal(await page.getByLabel('Condition summary',{exact:true}).innerText(),'trust >= 1.25');
  await capture(`${variant}-condition-compact`);
  if(variant!=='equation-v1')return;
  await open({state:'imagebutton',viewport:'wide'});await capture('equation-v1-imagebutton-wide');
  const imageBefore=await page.locator('.screen-render').getAttribute('src');
  await formula(1).fill('2');await page.getByRole('button',{name:'Apply action draft',exact:true}).click();
  assert.equal(await page.locator('.screen-render').getAttribute('src'),imageBefore);
  // Canvas selection uses the real renderer, but never activates game actions.
  await page.locator('.screen-render').click({position:{x:100,y:100},force:true});
  assert.equal(await page.locator('.screen-render').getAttribute('src'),imageBefore);
  await open({state:'stale',viewport:'wide'});await formula(1).fill('bonus');
  await page.getByRole('button',{name:'Apply action draft',exact:true}).click();
  assert.match(await page.locator('.sa-message').innerText(),/changed.*retained/);
  assert.equal(await formula(1).inputValue(),'bonus');await capture('equation-v1-stale-wide');
  await open({state:'protected',viewport:'wide'});
  assert.equal(await formula(1).count(),0);assert.match(await page.locator('.sa-body').innerText(),/timing differs/);await capture('equation-v1-protected-wide');
  await open({state:'unknown',viewport:'wide'});assert.match(await page.locator('.sa-warning').innerText(),/unknown.*No starting value/);await capture('equation-v1-unknown-wide');
  await open({state:'limits',viewport:'wide'});
  assert.equal(await page.getByRole('combobox',{name:'Add action',exact:true}).isDisabled(),true);
  await page.locator('.sa-examples summary').click();
  await page.getByRole('combobox',{name:'Action context',exact:true}).selectOption('panel');
  assert.equal(await page.getByRole('combobox',{name:'Add action',exact:true}).locator('option[value=finish]').count(),0);
  await page.locator('.sa-examples summary').click();
  await page.getByRole('combobox',{name:'Action context',exact:true}).selectOption('component');
  assert.match(await page.locator('.sa-body').innerText(),/Component actions stay in Source/);
  await open({state:'text',viewport:'wide'});
  const sample=page.getByRole('textbox',{name:'Money sample',exact:true});
  await sample.fill('2.5');assert.equal(await page.getByLabel('Editor text sample',{exact:true}).innerText(),'Balance: 2.5');
  const text=page.getByRole('textbox',{name:'Screen text',exact:true});await text.fill('Fare: ');
  await text.evaluate(e=>{e.focus();e.setSelectionRange(6,6);});await page.getByRole('button',{name:'Insert money',exact:true}).click();
  assert.equal(await text.inputValue(),'Fare: [money!q]');assert.equal(await text.evaluate(e=>e.selectionStart),15);
  await capture('equation-v1-text-wide');
  await open({state:'variables',viewport:'compact'});await capture('equation-v1-variables-compact');
  console.log('ok - ordered arithmetic editing, type guidance, grouping, context/limits, fixed decimal defaults, conditions, text samples and inert canvas');
}
