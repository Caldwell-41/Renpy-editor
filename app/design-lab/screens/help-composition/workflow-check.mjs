import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";

export default async function check({ page, open, variant = "workflow" }) {
  const output = new URL(`../../../../.toolchains/design-lab/pages/help-composition/${variant}/`, import.meta.url);
  await mkdir(output, { recursive: true });
  const capture = name => page.screenshot({ path: fileURLToPath(new URL(`${name}.png`, output)) });
  const show = state => open({ variant, state, theme: "dark" });
  const row = id => page.locator(`[data-row="${id}"]`);
  const selected = id => row(id).getAttribute("aria-selected");
  const order = () => page.locator("[data-row]").evaluateAll(rows => rows.map(row => row.dataset.row));
  const acceptedSource = async () => {
    await page.getByRole("button", { name: "View sample source", exact: true }).click();
    const source = await page.locator(".compose-source").innerText();
    await page.getByRole("button", { name: "Close source", exact: true }).click();
    return source;
  };
  const save = page.getByRole("button", { name: "Apply changes", exact: true });
  await page.setViewportSize({ width: 1440, height: 900 });
  await show("nested");
  const initial = await acceptedSource();
  await capture("01-select");
  await page.getByRole("button", { name: "Select Text button · Close", exact: true }).click();
  assert.equal(await selected("close"), "true");
  await row("body").click();
  assert.equal(await page.locator('[data-pick="body"]').getAttribute("data-selected"), "true");
  await page.getByRole("button", { name: "Select ancestor Vertical group", exact: true }).click();
  assert.equal(await selected("content"), "true");
  await row("body").dblclick();
  const text = page.getByRole("textbox", { name: "Text", exact: true });
  assert.equal(await text.isVisible(), true, "Double-click must enter Design");
  await text.fill("Click to continue. Escape opens the menu.");
  assert.equal(await acceptedSource(), initial, "Text preview must not apply a source change");
  await capture("03-edit");
  await page.getByRole("button", { name: "Back to elements", exact: true }).click();
  assert.match(await row("body").innerText(), /Draft/);
  await row("close").press("Enter");
  await page.getByRole("textbox", { name: "Button label", exact: true }).fill("Return");
  await page.getByRole("button", { name: /^Resume draft:/ }).click();
  assert.equal(await text.inputValue(), "Click to continue. Escape opens the menu.");
  await save.click();
  assert.match(await acceptedSource(), /Click to continue. Escape opens the menu./);
  // A second node's pending edit must survive Apply on the first node.
  await page.getByRole("button", { name: /^Resume draft:/ }).click();
  const label = page.getByRole("textbox", { name: "Button label", exact: true });
  assert.equal(await label.inputValue(), "Return");
  await page.getByRole("button", { name: "Cancel changes", exact: true }).click();
  await page.getByRole("button", { name: "Undo", exact: true }).click();
  assert.equal(await acceptedSource(), initial);
  await page.getByRole("button", { name: "Redo", exact: true }).click();
  assert.match(await acceptedSource(), /Click to continue. Escape opens the menu./);
  await page.getByRole("button", { name: "Back to elements", exact: true }).click();
  await row("body").click();
  const before = await order();
  const textSize = () => page.locator('[data-pick="body"]').evaluate(el => getComputedStyle(el).fontSize);
  const headingSize = () => page.locator('[data-pick="title"]').evaluate(el => getComputedStyle(el).fontSize);
  const originalTextSize = await textSize(), originalHeadingSize = await headingSize();
  await row("body").press("Alt+ArrowUp");
  assert.equal(await selected("body"), "true");
  assert((await order()).indexOf("body") < (await order()).indexOf("title"));
  assert.equal(await textSize(), originalTextSize, "Reorder must not restyle body text");
  assert.equal(await headingSize(), originalHeadingSize, "Reorder must not restyle the heading");
  await capture("04-reorder");
  await page.getByRole("button", { name: "Move down", exact: true }).click();
  assert.deepEqual(await order(), before);
  // Real pointer drag positions the body after Close.
  const bodyBounds = await row("body").boundingBox(), closeBounds = await row("close").boundingBox();
  await page.mouse.move(bodyBounds.x + 90, bodyBounds.y + bodyBounds.height / 2);
  await page.mouse.down();
  await page.mouse.move(closeBounds.x + 100, closeBounds.y + closeBounds.height - 3, { steps: 12 });
  await page.mouse.move(closeBounds.x + 100, closeBounds.y + closeBounds.height - 2);
  await page.mouse.up();
  assert((await order()).indexOf("body") > (await order()).indexOf("close"), "Pointer drop must reorder siblings");
  await page.getByRole("button", { name: "Undo", exact: true }).click();
  assert.deepEqual(await order(), before);
  await row("panel").click();
  const protectedOrder = await order();
  await page.getByRole("button", { name: "Move later", exact: true }).click();
  assert.match(await page.getByRole("alert").innerText(), /source-only/);
  assert.deepEqual(await order(), protectedOrder);
  assert.equal(await selected("panel"), "true");
  await capture("05-protected-reorder");

  await show("adding");
  const addText = page.getByRole("textbox", { name: "New element text", exact: true });
  await addText.fill("Press Escape to open the menu.");
  await capture("02-add");
  assert.equal(await acceptedSource(), initial);
  await page.getByRole("button", { name: "Add text", exact: true }).click();
  assert.equal(await selected("new-1"), "true");
  await row("new-1").press("Enter");
  await text.fill("A revised new line.");
  await text.press("Control+Enter");
  assert.match(await acceptedSource(), /A revised new line./);
  await page.getByRole("button", { name: "Back to elements", exact: true }).click();
  await page.getByRole("button", { name: "Move up", exact: true }).click();
  assert((await order()).indexOf("new-1") < (await order()).indexOf("close"));

  // Build a nested example through all five supported element types.
  await show("nested");
  await row("content").click();
  const addKind = async (kind, buttonName, value) => {
    await page.getByRole("button", { name: "Add element", exact: true }).click();
    await page.locator(`[data-kind="${kind}"]`).click();
    if (value) await addText.fill(value);
    await page.getByRole("button", { name: buttonName, exact: true }).click();
  };
  await addKind("fixed", "Add free layout group");
  await addKind("frame", "Add frame");
  await addKind("vbox", "Add vertical group");
  await addKind("text", "Add text", "Nested instructions");
  await addKind("textbutton", "Add button", "Done");
  await page.getByRole("button", { name: "Move up", exact: true }).click();
  const nestedSource = await acceptedSource();
  assert(nestedSource.indexOf('textbutton "Done"') < nestedSource.indexOf('text "Nested instructions"'));
  assert.match(nestedSource, /use custom_help_footer\(\)/);
  await row("new-1").click();
  await page.getByRole("button", { name: "Move up", exact: true }).click();
  assert((await order()).indexOf("new-1") < (await order()).indexOf("close"));
  assert((await order()).indexOf("new-5") > (await order()).indexOf("new-3"), "Group movement must retain descendants");
  // Occupied-frame refusal retains the exact input; Cancel leaves no accepted addition.
  await row("new-2").click();
  await page.getByRole("button", { name: "Add element", exact: true }).click();
  await addText.fill("Keep this draft");
  await page.getByRole("button", { name: "Add text", exact: true }).click();
  assert.match(await page.getByRole("alert").innerText(), /frame holds one child/);
  assert.equal(await addText.inputValue(), "Keep this draft");
  const beforeCancel = await acceptedSource();
  await addText.press("Escape");
  assert.equal(await acceptedSource(), beforeCancel);

  // Repeated container labels stay distinguishable in the tree and destination menu.
  await show("nested");
  await row("content").click();
  await addKind("vbox", "Add vertical group");
  await row("content").click();
  await addKind("vbox", "Add vertical group");
  assert.match(await row("new-1").innerText(), /Vertical group 1/);
  assert.match(await row("new-2").innerText(), /Vertical group 2/);
  await page.getByRole("button", { name: "Add element", exact: true }).click();
  const destinations = await page.getByLabel("Add inside", { exact: true }).locator("option").allTextContents();
  assert.equal(destinations.length, new Set(destinations).size);
  await page.getByRole("button", { name: "Cancel", exact: true }).click();

  await show("conflict");
  const draft = await text.inputValue();
  await save.click();
  assert.match(await page.getByRole("alert").innerText(), /Source changed/);
  assert.equal(await text.inputValue(), draft);
  await capture("06-conflict");
  await page.getByRole("button", { name: "Review source conflict", exact: true }).click();
  await page.getByRole("button", { name: "Simulate source refresh", exact: true }).click();
  assert.equal(await text.inputValue(), draft);
  await save.click();
  assert.equal(await save.isDisabled(), true);
  await page.setViewportSize({ width: 560, height: 640 });
  await show("nested");
  await capture("07-compact");
  await page.getByRole("button", { name: "Edit text", exact: true }).click();
  await text.fill("Compact draft retained");
  await page.getByRole("button", { name: "Show canvas", exact: true }).click();
  const canvasBounds = await page.getByRole("region", { name: "Screen canvas" }).boundingBox();
  assert(canvasBounds.y >= 0 && canvasBounds.y < 640, "Show canvas must reveal the preview");
  await page.getByRole("button", { name: "Back to editing", exact: true }).click();
  assert.equal(await text.inputValue(), "Compact draft retained");
  assert.equal(await text.evaluate(el => el === document.activeElement), true);

}
