import assert from 'node:assert/strict';
export default async function check({page,open}) {
  for(const variant of ['manuscript','stage']) {
    await open({variant});
    const dialogue=page.getByRole('textbox',{name:'Dialogue',exact:true});
    const original=await dialogue.inputValue();
    await dialogue.fill('Keep this station draft. Café 雪.');
    await page.getByRole('button',{name:'Select Narration beat 3',exact:true}).click();
    await page.getByRole('button',{name:'Select Dialogue beat 4',exact:true}).click();
    assert.equal(await dialogue.inputValue(),'Keep this station draft. Café 雪.');
    await page.getByRole('button',{name:'Hide preview',exact:true}).click();
    assert.equal(await dialogue.inputValue(),'Keep this station draft. Café 雪.');
    await page.getByRole('button',{name:'Show preview',exact:true}).click();
    await page.getByRole('button',{name:'Save beat',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('.lp-status')?.textContent==='Saved in sample');
    await page.getByRole('button',{name:'Undo',exact:true}).click();
    assert.equal(await dialogue.inputValue(),original);
    await page.getByRole('button',{name:'Redo',exact:true}).click();
    assert.equal(await dialogue.inputValue(),'Keep this station draft. Café 雪.');
    await dialogue.fill('Discard this one');
    await page.getByRole('button',{name:'Discard beat draft',exact:true}).click();
    await page.getByRole('button',{name:'Keep editing',exact:true}).click();
    assert.equal(await dialogue.inputValue(),'Discard this one');
    await page.getByRole('button',{name:'Discard beat draft',exact:true}).click();
    await page.getByRole('button',{name:'Discard draft',exact:true}).click();
    assert.equal(await dialogue.inputValue(),'Keep this station draft. Café 雪.');
    await page.getByRole('button',{name:'Select Choice beat 7',exact:true}).click();
    await page.getByRole('textbox',{name:'Option 1 text',exact:true}).fill('Follow the bell');
    await page.getByRole('button',{name:'Add option',exact:true}).click();
    assert.equal(await page.getByRole('textbox',{name:'Option 3 text',exact:true}).inputValue(),'New option');
    await page.getByRole('button',{name:'Save beat',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('.lp-status')?.textContent==='Saved in sample');
    await page.getByRole('button',{name:'Select Condition beat 5',exact:true}).click();
    await page.getByRole('textbox',{name:'If condition',exact:true}).fill('trust >= 5');
    await page.getByRole('button',{name:'Add Else If',exact:true}).click();
    assert.equal(await page.getByRole('textbox',{name:'Else If condition',exact:true}).inputValue(),'trust >= 3');
    await page.getByRole('button',{name:'Save beat',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('.lp-status')?.textContent==='Saved in sample');
    await page.getByRole('button',{name:'Select Dialogue beat 4',exact:true}).click();
    await page.getByRole('button',{name:'Assist…',exact:true}).click();
    await page.getByRole('button',{name:'Prepare request',exact:true}).click();
    await page.getByRole('button',{name:'Generate sample',exact:true}).click();
    await page.getByRole('button',{name:'Cancel generation',exact:true}).click();
    assert.equal(await page.getByRole('button',{name:'Generate sample',exact:true}).isVisible(),true);
    await page.getByRole('button',{name:'Generate sample',exact:true}).click();
    await page.getByRole('button',{name:'Accept and save',exact:true}).click();
    assert.match(await dialogue.inputValue(),/The bell rang twice/);
    await page.getByRole('button',{name:'Undo',exact:true}).click();
    assert.equal(await dialogue.inputValue(),'Keep this station draft. Café 雪.');
    await page.getByRole('button',{name:'Writing focus',exact:true}).click();
    assert.equal(await page.getByLabel('Illustrative game preview').isVisible(),false);
    await page.getByRole('button',{name:'Exit writing focus',exact:true}).click();
    assert.equal(await page.getByLabel('Illustrative game preview').isVisible(),true);
    await open({variant,state:'error'});
    await dialogue.fill('Keep after refusal');await page.getByRole('button',{name:'Save beat',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('.lp-status')?.textContent?.startsWith('Simulated save failure'));
    assert.equal(await dialogue.inputValue(),'Keep after refusal');
    await open({variant,state:'empty'});
    await page.getByRole('button',{name:'Write the first beat',exact:true}).click();
    await page.getByRole('dialog',{name:'Add a beat'}).getByRole('button',{name:'Add beat',exact:true}).click();
    assert.equal(await dialogue.inputValue(),'');
    await dialogue.fill('The first service.');await page.getByRole('button',{name:'Save beat',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('.lp-status')?.textContent==='Saved in sample');
    await open({variant,state:'long',viewport:'compact'});await dialogue.fill('Long sample draft');
    await page.getByRole('button',{name:'Save drafts',exact:true}).click();
    assert.equal(await page.getByRole('button',{name:'Save drafts',exact:true}).isDisabled(),true);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  }
}
