import assert from "node:assert/strict";
import { fileURLToPath } from "node:url";

export default async function check({ page, open }) {
  const field = key => page.getByRole("textbox", { name: key === "world" ? "World & starting situation" : "Tone & writing style", exact: true });
  const button = name => page.getByRole("button", { name, exact: true });
  const more = () => page.getByLabel("More Lorebook actions", { exact: true });
  const save = () => button("Save changes");
  const feedback = () => page.locator(".lb-notice");
  const settle = () => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  async function capture(name) { await settle(); await page.screenshot({ path: fileURLToPath(new URL(`../../../../.toolchains/design-lab/pages/lorebook/${name}.png`, import.meta.url)) }); }
  for (const variant of ["manuscript", "parallel"]) {
    await page.setViewportSize({ width: 1100, height: 720 }); await open({ variant });
    const originalWorld = await field("world").inputValue();
    assert.equal(await save().isDisabled(), true);
    const draft = "A retained fictional draft. Café 雪.";
    await field("world").fill(draft);
    const nav = page.getByRole("button", { name: /^(Expand|Collapse) navigation$/, exact: true });
    await nav.click(); assert.equal(await field("world").inputValue(), draft); await nav.click();
    await button("Version history").click();
    assert.match(await page.getByRole("dialog", { name: "Lorebook version history" }).innerText(), /read-only/);
    await button("Close version history").click();
    assert.equal(await button("Version history").evaluate(e => e === document.activeElement), true);
    assert.equal(await field("world").inputValue(), draft);
    await more().click(); await button("Saved reference entries").click();
    const retained = page.getByRole("dialog", { name: "Saved reference entries" });
    await retained.getByText("Approval and source check", { exact: true }).nth(1).click();
    assert.match(await retained.innerText(), /Approval is blocked because the supporting scene has changed/);
    assert.match(await retained.innerText(), /Revision 1 remains the approved reference/);
    assert.equal(await retained.getByRole("button").count(), 1);
    await page.keyboard.press("Escape"); await retained.waitFor({ state: "detached" });
    assert.equal(await field("world").inputValue(), draft);
    assert.equal(await more().evaluate(e => e === document.activeElement), true);
    await button("Preview request context").click();
    const request = page.getByRole("dialog", { name: "Request context preview" });
    assert.match(await request.innerText(), /last saved version/);
    assert.equal((await page.locator(".lb-request-context").innerText()).includes(draft), false);
    await page.getByLabel("Include project Lorebook in this request", { exact: true }).uncheck();
    assert.equal(await page.locator(".lb-request-context").getAttribute("data-included"), "false");
    assert.match(await page.locator(".lb-token-note").innerText(), /0 Lorebook tokens/);
    await button("Close request context preview").click();
    await button("Preview request context").click();
    assert.equal(await page.getByLabel("Include project Lorebook in this request", { exact: true }).isChecked(), true);
    await page.keyboard.press("Escape");
    await more().click(); await button("Reload Lorebook").click();
    assert.equal(await field("world").inputValue(), draft); assert.match(await feedback().innerText(), /draft is retained/);
    await button("Story").click();
    await page.getByRole("dialog", { name: "Leave this sample?" }).waitFor();
    await button("Keep editing").click(); assert.equal(await field("world").inputValue(), draft);
    await save().click();
    assert.equal(await field("world").isDisabled(), true);
    assert.equal(await button("Preview request context").isDisabled(), true);
    await page.waitForFunction(() => document.querySelector(".lb-notice")?.textContent === "Saved in sample. Nothing was sent.");
    assert.equal(await save().isDisabled(), true);
    await more().click(); await button("Undo").click(); assert.equal(await field("world").inputValue(), originalWorld);
    await more().click(); await button("Redo").click(); assert.equal(await field("world").inputValue(), draft);
    await field("world").fill("Discard this draft"); await button("Discard changes").click();
    await button("Keep editing").click(); assert.equal(await field("world").inputValue(), "Discard this draft");
    await button("Discard changes").click(); await button("Discard draft").click();
    assert.equal(await field("world").inputValue(), draft);
    await field("tone").fill("雪".repeat(3400)); await save().click();
    assert.equal(await field("tone").getAttribute("aria-invalid"), "true");
    assert.equal(await field("tone").evaluate(e => e === document.activeElement), true);
    assert.match(await feedback().innerText(), /Correct the marked field/);
    await open({ variant, state: "error" }); await field("world").fill("Keep this after refusal"); await save().click();
    await page.waitForFunction(() => document.querySelector(".lb-notice")?.textContent.startsWith("Simulated save failure"));
    assert.equal(await field("world").inputValue(), "Keep this after refusal"); assert.equal(await save().isEnabled(), true);
    await capture(`${variant}-light-error`);
    await save().click(); await page.waitForFunction(() => document.querySelector(".lb-notice")?.textContent === "Saved in sample. Nothing was sent.");
    await open({ variant, state: "empty" }); assert.equal(await field("world").inputValue(), "");
    await button("Version history").click(); assert.match(await page.getByRole("dialog").innerText(), /No saved versions yet/); await page.keyboard.press("Escape");
    await field("tone").fill("Leave room for warmth."); await save().click();
    await page.waitForFunction(() => document.querySelector(".lb-notice")?.textContent === "Saved in sample. Nothing was sent.");
    await page.setViewportSize({ width: 560, height: 640 }); await open({ variant, state: "long", theme: "dark", viewport: "compact" });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    assert(await page.locator(".lb-body").evaluate(e => e.scrollHeight > e.clientHeight));
    assert(await field("world").evaluate(e => Math.abs(e.scrollHeight - e.clientHeight) <= 3));
    await page.locator(".lb-body").evaluate(e => e.scrollTop = e.scrollHeight);
    const bounds = await save().boundingBox();
    assert(bounds && bounds.x >= 0 && bounds.y >= 0 && bounds.x + bounds.width <= 560 && bounds.y + bounds.height <= 640, "Save remains reachable below long writing.");
    await field("tone").fill("Compact draft stays here.");
    await button("Version history").click(); await page.keyboard.press("Escape");
    assert.equal(await field("tone").inputValue(), "Compact draft stays here.");
    await capture(`${variant}-dark-long-compact`);
    await page.reload(); await page.locator('#preview[data-ready="true"]').waitFor();
    assert.notEqual(await field("tone").inputValue(), "Compact draft stays here.");
  }
}
