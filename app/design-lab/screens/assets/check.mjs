import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
export default async function check({ page, open }) {
  for (const variant of ['shelves', 'desk']) {
    await page.setViewportSize({ width: 1100, height: 720 });
    await open({ variant });
    const cards = page.locator('.aa-card');
    assert.equal(await cards.count(), 7);
    await page.getByRole('button', { name: 'Backgrounds 3', exact: true }).click();
    assert.equal(await cards.count(), 3);
    await page.getByLabel('Search assets', { exact: true }).fill('bookshop');
    assert.equal(await cards.count(), 1);
    await page.getByRole('button', { name: 'Inspect After-hours bookshop', exact: true }).click();
    await page.locator('.aa-inspector summary').click();
    assert.match(await page.locator('.aa-inspector .aa-path').innerText(), /game\/images\/bookshop.png/);
    await page.getByLabel('Search assets', { exact: true }).fill('nothing-matches');
    assert.equal(await page.getByRole('heading', { name: 'No matching assets', exact: true }).isVisible(), true);
    await page.getByRole('button', { name: 'Clear search & filters', exact: true }).click();
    const before = await page.locator('.aa-items').getAttribute('class');
    await page.locator('.aa-toolbar button').click();
    assert.notEqual(await page.locator('.aa-items').getAttribute('class'), before);
    await page.getByRole('button', { name: 'Inspect Rain on the windows', exact: true }).click();
    await page.getByRole('button', { name: 'Retry preview', exact: true }).click();
    assert.equal(await page.getByRole('heading', { name: 'Preview unavailable', exact: true }).count(), 0);
    await page.getByRole('button', { name: 'Inspect The last departure', exact: true }).click();
    assert.match(await page.locator('.aa-audio-note').innerText(), /Audio playback is planned/);
    assert.equal(await page.locator('audio').count(), 0);
    await page.getByRole('button', { name: 'Asset maintenance', exact: true }).click();
    await page.getByRole('button', { name: "Repair Ren'Py names", exact: true }).click();
    assert.match(await page.locator('.lp-status').innerText(), /repaired in memory/);
    await page.getByRole('button', { name: 'Inspect Tram bell', exact: true }).click();
    assert.equal(await page.locator('.aa-warning').count(), 0);

    await page.getByRole('button', { name: 'Import assets', exact: true }).click();
    await page.getByText('Try a selection problem', { exact: true }).click();
    await page.getByRole('button', { name: 'Try refused file', exact: true }).click();
    assert.match(await page.getByRole('alert').innerText(), /archive.zip was refused/);
    await page.getByRole('button', { name: 'Use selected samples', exact: true }).click();
    let rows = page.locator('[data-stage-row]');
    assert.equal(await rows.count(), 3);
    await rows.nth(0).getByLabel('Display name', { exact: true }).fill('');
    await rows.nth(0).getByLabel("Ren'Py name", { exact: true }).fill('12 invalid');
    await rows.nth(1).getByLabel('Character', { exact: true }).selectOption('');
    await page.getByRole('button', { name: 'Import 3 samples', exact: true }).click();
    assert.match(await page.locator('.aa-batch-feedback').innerText(), /Nothing was imported/);
    assert.equal(await cards.count(), 7);
    await rows.nth(0).getByLabel('Display name', { exact: true }).fill('Sunrise bridge');
    await page.getByRole('button', { name: 'Retry import', exact: true }).click();
    assert.match(await rows.nth(0).innerText(), /valid Ren'Py name/);
    await rows.nth(0).getByLabel("Ren'Py name", { exact: true }).fill('sunrise_bridge');
    await rows.nth(1).getByLabel('Character', { exact: true }).selectOption('Mira');
    await rows.nth(1).getByLabel('Expression', { exact: true }).fill('joy');
    await rows.nth(2).getByLabel('Use as', { exact: true }).selectOption('sfx');
    await page.getByRole('button', { name: 'Keep batch & close', exact: true }).click();
    await page.getByRole('button', { name: 'Story', exact: true }).click();
    await page.getByRole('dialog', { name: 'Leave this sample?', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Keep editing', exact: true }).click();
    await page.getByRole('button', { name: 'Review 3 staged', exact: true }).click();
    rows = page.locator('[data-stage-row]');
    assert.equal(await rows.nth(0).getByLabel('Display name', { exact: true }).inputValue(), 'Sunrise bridge');
    assert.equal(await rows.nth(1).getByLabel('Expression', { exact: true }).inputValue(), 'joy');
    assert.equal(await rows.nth(2).getByLabel('Use as', { exact: true }).inputValue(), 'sfx');
    await page.getByText('Try an import problem', { exact: true }).click();
    await page.getByLabel('Interrupt the next import once', { exact: true }).check();
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    await page.screenshot({ path: fileURLToPath(new URL(`../../../../.toolchains/design-lab/pages/assets/${variant}-import-review.png`, import.meta.url)) });
    await page.getByRole('button', { name: 'Import 3 samples', exact: true }).click();
    await page.getByText('2 imported. One sample needs a retry.', { exact: true }).waitFor();
    assert.equal(await rows.count(), 1);
    assert.equal(await cards.count(), 9);
    await page.getByRole('button', { name: 'Retry import', exact: true }).click();
    await page.getByRole('heading', { name: '1 asset added', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Back to library', exact: true }).click();
    assert.equal(await cards.count(), 10);
    await page.getByRole('button', { name: 'Import assets', exact: true }).click();
    await page.getByRole('button', { name: 'Cancel selection', exact: true }).click();
    assert.equal(await cards.count(), 10);
    await page.getByRole('button', { name: 'Import assets', exact: true }).click();
    await page.getByRole('button', { name: 'Use selected samples', exact: true }).click();
    await page.getByRole('button', { name: 'Discard batch', exact: true }).click();
    assert.equal(await page.getByRole('button', { name: 'Import assets', exact: true }).isVisible(), true);
    assert.equal(await page.locator('input[type="file"]').count(), 0);

    await open({ variant, state: 'error' });
    await page.getByRole('button', { name: 'Retry preview', exact: true }).click();
    await open({ variant, state: 'empty' });
    assert.equal(await page.getByRole('heading', { name: 'Give this story a setting', exact: true }).isVisible(), true);
    await page.getByRole('button', { name: 'Choose sample assets', exact: true }).click();
    await page.keyboard.press('Escape');
    assert.equal(await page.getByRole('button', { name: 'Choose sample assets', exact: true }).evaluate(e => e === document.activeElement), true);
    await page.setViewportSize({ width: 560, height: 640 });
    await open({ variant, state: 'long', theme: 'dark', viewport: 'compact' });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.getByRole('button', { name: 'Import assets', exact: true }).click();
    await page.getByRole('button', { name: 'Use selected samples', exact: true }).click();
    await page.getByRole('button', { name: 'Keep batch & close', exact: true }).click();
    await page.getByRole('button', { name: 'Expand navigation', exact: true }).click();
    await page.getByRole('button', { name: 'Collapse navigation', exact: true }).click();
    await page.getByRole('button', { name: 'Review 3 staged', exact: true }).click();
    assert.equal(await page.locator('[data-stage-row]').count(), 3);
    assert.equal(await page.locator('.aa-staged-list').evaluate(e => e.scrollHeight > e.clientHeight), true);
    assert.equal(await page.getByRole('button', { name: 'Import 3 samples', exact: true }).isVisible(), true);
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    await page.screenshot({ path: fileURLToPath(new URL(`../../../../.toolchains/design-lab/pages/assets/${variant}-dark-compact-import.png`, import.meta.url)) });
    await page.keyboard.press('Escape');
    await page.getByRole('button', { name: 'Review 3 staged', exact: true }).click();
    assert.equal(await page.locator('[data-stage-row]').count(), 3);
    await page.getByRole('button', { name: 'Discard batch', exact: true }).click();
  }
}
