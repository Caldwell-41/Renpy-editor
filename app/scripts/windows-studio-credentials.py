def select_acceptance(combined_attempts=3, replacement=False, sequence=None):
    global OUTPUT, ACCEPTANCE, COMBINED_ATTEMPTS, REPLACEMENT, SEQUENCE
    if combined_attempts not in (3, 10) or replacement and combined_attempts != 10:
        raise ValueError("Explicit selected combined allowance required")
