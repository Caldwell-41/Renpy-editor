def combined_budget_check(kind=None):
    if COMPLETION_RUN is not None:
        builds = len(list(OUTPUT.glob("build-*-attempt.json")))
        runs = len(list(OUTPUT.glob("run-*-attempt.json")))
        if builds > 6 or runs > 9 or (kind == "build" and builds >= 6) or (kind == "launch" and runs >= 9):
            raise ValueError("Additional allowance exhausted: two builds / three launches above four / six")
        return {"combinedAttemptLimit":15,"combinedAttemptsBefore":builds+runs,
                "additionalBuildsBefore":builds-4,"additionalLaunchesBefore":runs-6}
    consumed = len(list(OUTPUT.glob("build-*-attempt.json"))) + len(list(OUTPUT.glob("run-*-attempt.json")))
    if consumed >= COMBINED_ATTEMPTS:
        raise ValueError("Selected combined build/launch allowance exhausted; no renewal")
