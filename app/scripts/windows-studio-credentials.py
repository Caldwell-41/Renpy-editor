def validate_observations(phase, value):
    expected = (["alpha-entry", "alpha-refusal", "alpha-retry", "gamma-entry", "gamma-confirmation", "cancel-entry", "stale-refusal", "cancel", "get-alpha-1", "get-alpha-2", "exit"]
                if phase == 1 else ["get-alpha", "beta-entry", "beta-confirmation", "reload-required", "read-only-retry", "get-beta", "exit"])
    if COMPLETION_RUN is not None and phase == 2:
        expected = ["reopened", "get-alpha", "beta-entry", "beta-confirmation", "reload-required", "read-only-retry", "get-beta", "removed", "complete", "exit"]
    if value.get("phase") != phase or value.get("run") != selected_run(phase) or [e.get("name") for e in value.get("events", [])] != expected:
        raise ValueError("Ordered native/UI observation evidence missing")
    last = 0
    for event in value["events"]:
        start, end = event.get("startSeconds", -1), event.get("endSeconds", -1)
        limit = OBSERVATION_SECONDS if COMPLETION_RUN is not None and phase == 2 else 120 if event["name"].endswith("-entry") else 17 if event["name"].startswith("get-") else 15
        if not 0 <= start <= end <= RUN_SECONDS or start < last or event.get("passed") is not True:
            raise ValueError("Native action order/result/deadline refused")
        validate_elapsed(end - start, limit)
        if event["name"].startswith("get-"):
            validate_elapsed(event.get("requestSeconds"), 15)
            cleanup = event.get("cleanupSeconds")
            if (not isinstance(cleanup, (int, float)) or not 0 <= cleanup <= 2
                    or (COMPLETION_RUN is None and event["requestSeconds"] + cleanup > end - start)):
                raise ValueError("GET/cleanup subdeadline refused")
        last = end
    required = (["maskedNativeField", "failedSaveRetainedInput", "retryWithoutRetyping", "staleSaveRetainedInput", "cancelAfterExactRestore"]
                if phase == 1 else ["maskedNativeField", "exactReloadStatus", "allMutationDiscoveryControlsDisabled", "readOnlyRetryEnabled", "restoredConfiguredA"])
    if value.get("observed") != dict.fromkeys(required, True):
        raise ValueError("Native UI capture/refusal/restoration proof missing")
    # Confirmation/fault/restore work must stay inside each original entry cap.
    events = {e["name"]:e for e in value["events"]}
    pairs = [("alpha-entry", "alpha-retry"), ("gamma-entry", "gamma-confirmation"), ("cancel-entry", "cancel")] if phase == 1 else [("beta-entry", "beta-confirmation")]
    for first, final in pairs:
        validate_elapsed(events[final]["endSeconds"] - events[first]["startSeconds"], 120)

