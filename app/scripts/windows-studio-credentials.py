def await_observations(prefix, started, exited_monotonic=None):
    # The host observes actual exit before publishing. Completion gives receipt
    # collection its own observation bound, separately from application shutdown.
    deadline = min((exited_monotonic if exited_monotonic is not None else time.monotonic()) + (OBSERVATION_SECONDS if COMPLETION_RUN else 15),
                   started + RUN_SECONDS)
    path = OUTPUT / f"{prefix}-observed.json"
    while not path.is_file():
        if time.monotonic() >= deadline:
            raise ValueError("Actual native observation receipt missing within exit/launch cap")
        time.sleep(0.02)
    if time.monotonic() >= deadline:
        raise ValueError("Actual native observation receipt late")
    return read(path)

def native_input_clock(run, entry_start_seconds):
    """File-only clock guard to call immediately before supported native input."""
    if not ACCEPTANCE or run not in (selected_run(1), selected_run(2)):
        raise ValueError("Selected native launch clock required")
    prefix = f"run-{run}"
    if (OUTPUT / f"{prefix}.json").exists():
        raise ValueError("Native run is terminal; no UI reacquisition/input")
    launch = read(OUTPUT / f"{prefix}-launch.json")
    now = time.monotonic()
    elapsed = now - launch["startedMonotonic"]
    if (not isinstance(entry_start_seconds, (int, float)) or isinstance(entry_start_seconds, bool)
            or not 0 <= entry_start_seconds <= elapsed < RUN_SECONDS
            or elapsed - entry_start_seconds >= 120):
        raise ValueError("Whole entry/launch clock exhausted; native input refused")
    return {"monotonic":now,"seconds":elapsed,"entryElapsedSeconds":elapsed-entry_start_seconds}

def pid_absent(pid):
    listing = subprocess.run(["tasklist", "/FI", f"PID eq {pid}", "/FO", "CSV", "/NH"], capture_output=True, text=True, timeout=2, check=True).stdout
    return f'"{pid}"' not in listing

def confirm_reload():
    if not ACCEPTANCE:
        raise ValueError("Reload acknowledgement is selected acceptance phase 2 only")
    run = selected_run(2)
    prefix = f"run-{run}"
    launch = read(OUTPUT / f"{prefix}-launch.json")
    if (OUTPUT / f"{prefix}.json").exists() or time.monotonic() - launch["startedMonotonic"] >= RUN_SECONDS or pid_absent(launch["pid"]):
        raise ValueError("Recorded selected phase 2 is not live within deadline")
    root = root_from_state()
    if read(root / ".studio-windows-step.json") != {"phase":"2", "step":"beta-reload-required"}:
        raise ValueError("Confirmed beta reload UI is not current")
    observed = read(OUTPUT / f"{prefix}-reload-observed.json")
    if (observed.get("run") != run or observed.get("phase") != 2
            or observed.get("saveStatus") != read(RELOAD)["expectedResponse"]["saveStatus"]
            or observed.get("controlsDisabled") is not True or observed.get("retryEnabled") is not True
            or observed.get("profilesSha256") != sha(root / ".studio-windows-2-beta-reload-required.json")
            or not observed.get("captures")):
        raise ValueError("Actual Windows reload UI capture missing")
    validate_elapsed(observed["endSeconds"] - observed["startSeconds"], OBSERVATION_SECONDS if COMPLETION_RUN else 15)
    if not 0 <= observed["startSeconds"] < observed["endSeconds"] <= time.monotonic() - launch["startedMonotonic"] <= RUN_SECONDS:
        raise ValueError("Reload UI capture deadline refused")
    for capture in observed["captures"]:
        path = OUTPUT / capture["file"]
        if path.resolve().parent != OUTPUT.resolve() or path.suffix.lower() not in (".png", ".jpg", ".jpeg", ".webp") or sha(path) != capture["sha256"] or path.stat().st_size != capture["bytes"]:
            raise ValueError("Owned Windows UI capture identity refused")
    # The unchanged packaged fixture uses logical acknowledgement 7. External
    # launch/capture receipts retain the selected physical run identity.
    write(root / ".studio-windows-reload-observed.json", {"run":7,"phase":2,"observed":True}, exclusive=True)

